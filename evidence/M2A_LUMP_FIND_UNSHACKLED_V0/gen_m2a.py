def le_emit(out, tag, base_off):
    out.append('mov A, C')
    out.append(f'add A, {base_off}')
    out.append('load B, A')
    out.append('mov A, B')
    out.append('mov B, C')
    out.append(f'add B, {base_off + 1}')
