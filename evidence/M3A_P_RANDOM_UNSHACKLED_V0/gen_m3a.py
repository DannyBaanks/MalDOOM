"""Generate M3A_P_RANDOM.eir (hand-authored EIR, deterministic).

Doom's P_Random (m_random.c): prndindex=(prndindex+1)&0xff; return rndtable[prndindex].
Tick framing mirrors P_Ticker skeleton: per tick do 8 draws, then leveltime++.
3 ticks per run, state (leveltime, prndindex) carried in-VM across ticks.
stdin: leveltime 4B LE + prndindex 1B, hex-framed (10 ASCII chars).
Table: Doom's 256-byte rndtable embedded as immediates at 5000-5255.
Slots: 1999 hexpair ret; 1998 idx; 1997 leveltime.
"""
import pathlib
import re

tmp = pathlib.Path(r'C:\Users\progr\AppData\Local\Temp\opencode\m3a_prandom')
tmp.mkdir(parents=True, exist_ok=True)

src = pathlib.Path(
    r'C:\Development\ISyCo Git\MALDOOM\vendor\doomgeneric\doomgeneric\m_random.c'
).read_text()
nums = [int(x) for x in re.findall(r'\d+', src.split('rndtable[256] = {', 1)[1].split('};', 1)[0])]
assert len(nums) == 256, len(nums)
assert nums[:4] == [0, 8, 109, 220] and nums[-3:] == [163, 236, 249], (nums[:4], nums[-3:])
print('rndtable extracted:', len(nums))

L = []
L.append('# M3A_P_RANDOM: Doom P_Random ticks inside the VM. Table = vendored rndtable.')
L.append('# stdin: leveltime(4B LE) + prndindex(1B), hex-framed = 10 chars.')
L.append('jmp main')
L.append('hexpair:')
L.append('mov D, 0')
L.append('jlt hex_hi09, A, 48')
L.append('jgt hex_hiAF, A, 57')
L.append('sub A, 48')
L.append('jmp hex_hidone')
L.append('hex_hiAF:')
L.append('jlt hex_hierr, A, 65')
L.append('jgt hex_hiAF2, A, 70')
L.append('sub A, 55')
L.append('jmp hex_hidone')
L.append('hex_hiAF2:')
L.append('jlt hex_hierr, A, 97')
L.append('jgt hex_hierr, A, 102')
L.append('sub A, 87')
L.append('hex_hidone:')
L.append('mov D, A')
L.append('add D, D')
L.append('add D, D')
L.append('add D, D')
L.append('add D, D')
L.append('jlt hex_lo09, B, 48')
L.append('jgt hex_loAF, B, 57')
L.append('sub B, 48')
L.append('add D, B')
L.append('load C, 1999')
L.append('jmp C')
L.append('hex_loAF:')
L.append('jlt hex_loerr, B, 65')
L.append('jgt hex_loAF2, B, 70')
L.append('sub B, 55')
L.append('add D, B')
L.append('load C, 1999')
L.append('jmp C')
L.append('hex_loAF2:')
L.append('jlt hex_loerr, B, 97')
L.append('jgt hex_loerr, B, 102')
L.append('sub B, 87')
L.append('add D, B')
L.append('load C, 1999')
L.append('jmp C')
L.append('hex_hi09:')
L.append('hex_lo09:')
L.append('hex_hierr:')
L.append('hex_loerr:')
L.append('putc 72')
L.append('putc 10')
L.append('exit')
L.append('main:')
for i, v in enumerate(nums):
    L.append(f'mov A, {v}')
    L.append(f'store A, {5000 + i}')
L.append('# decode leveltime 4B LE -> A, check top byte 0 (24-bit)')
L.append('mov BP, 6000')
L.append('mov SP, 5')
L.append('dec_loop:')
L.append('jeq dec_done, SP, 0')
L.append('mov C, dec_ret')
L.append('store C, 1999')
L.append('getc A')
L.append('getc B')
L.append('jmp hexpair')
L.append('dec_ret:')
L.append('store D, BP')
L.append('add BP, 1')
L.append('sub SP, 1')
L.append('jmp dec_loop')
L.append('dec_done:')
L.append('load D, 6000')
L.append('mov A, D')
L.append('load D, 6001')
L.append('mov B, D')
for _ in range(8):
    L.append('add B, B')
L.append('add A, B')
L.append('load D, 6002')
L.append('mov B, D')
for _ in range(16):
    L.append('add B, B')
L.append('add A, B')
L.append('load D, 6003')
L.append('jeq lt_ok, D, 0')
L.append('putc 88')
L.append('putc 10')
L.append('exit')
L.append('lt_ok:')
L.append('store A, 1997')
L.append('load D, 6004')
L.append('store D, 1998')
L.append('# 3 ticks x 8 draws')
L.append('mov SP, 0')
L.append('tick_loop:')
L.append('jge ticks_done, SP, 3')
L.append('mov BP, 0')
L.append('draw_loop:')
L.append('jge draw_done, BP, 8')
L.append('load D, 1998')
L.append('add D, 1')
L.append('jeq idx_wrap, D, 256')
L.append('jmp idx_nowrap')
L.append('idx_wrap:')
L.append('mov D, 0')
L.append('idx_nowrap:')
L.append('store D, 1998')
L.append('mov A, 5000')
L.append('add A, D')
L.append('load A, A')
L.append('# emit A (0-255) decimal')
L.append('mov B, 0')
L.append('mov D, 0')
L.append('em100:')
L.append('jlt e100, A, 100')
L.append('sub A, 100')
L.append('add D, 1')
L.append('jmp em100')
L.append('e100:')
L.append('jgt w100, D, 0')
L.append('jgt w100, B, 0')
L.append('jmp n100')
L.append('w100:')
L.append('add D, 48')
L.append('putc D')
L.append('mov B, 1')
L.append('n100:')
L.append('mov D, 0')
L.append('em10:')
L.append('jlt e10, A, 10')
L.append('sub A, 10')
L.append('add D, 1')
L.append('jmp em10')
L.append('e10:')
L.append('jgt w10, D, 0')
L.append('jgt w10, B, 0')
L.append('jmp n10')
L.append('w10:')
L.append('add D, 48')
L.append('putc D')
L.append('mov B, 1')
L.append('n10:')
L.append('add A, 48')
L.append('putc A')
L.append('putc 10')
L.append('add BP, 1')
L.append('jmp draw_loop')
L.append('draw_done:')
L.append('load A, 1997')
L.append('add A, 1')
L.append('store A, 1997')
L.append('add SP, 1')
L.append('jmp tick_loop')
L.append('ticks_done:')
L.append('# emit final leveltime then final idx')
L.append('load A, 1997')
L.append('mov B, 0')
for div in [1000000, 100000, 10000, 1000, 100, 10]:
    L.append('mov D, 0')
    L.append(f'lt_d{div}:')
    L.append(f'jlt lt_e{div}, A, {div}')
    L.append(f'sub A, {div}')
    L.append('add D, 1')
    L.append(f'jmp lt_d{div}')
    L.append(f'lt_e{div}:')
    L.append(f'jgt lt_w{div}, D, 0')
    L.append(f'jgt lt_w{div}, B, 0')
    L.append(f'jmp lt_n{div}')
    L.append(f'lt_w{div}:')
    L.append('add D, 48')
    L.append('putc D')
    L.append('mov B, 1')
    L.append(f'lt_n{div}:')
L.append('add A, 48')
L.append('putc A')
L.append('putc 10')
L.append('load A, 1998')
L.append('mov B, 0')
L.append('mov D, 0')
L.append('ix100:')
L.append('jlt ix100e, A, 100')
L.append('sub A, 100')
L.append('add D, 1')
L.append('jmp ix100')
L.append('ix100e:')
L.append('jgt ix100w, D, 0')
L.append('jmp ix10s')
L.append('ix100w:')
L.append('add D, 48')
L.append('putc D')
L.append('mov B, 1')
L.append('ix10s:')
L.append('mov D, 0')
L.append('ix10:')
L.append('jlt ix10e, A, 10')
L.append('sub A, 10')
L.append('add D, 1')
L.append('jmp ix10')
L.append('ix10e:')
L.append('jgt ix10w, D, 0')
L.append('jgt ix10w, B, 0')
L.append('jmp ix1s')
L.append('ix10w:')
L.append('add D, 48')
L.append('putc D')
L.append('mov B, 1')
L.append('ix1s:')
L.append('add A, 48')
L.append('putc A')
L.append('putc 10')
L.append('exit')
(tmp / 'M3A_P_RANDOM.eir').write_text('\n'.join(L) + '\n')
print('lines=', len(L))
